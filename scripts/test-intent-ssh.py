#!/usr/bin/env python3
"""Exercise obsolete-hook retirement through Make and real ssh -G."""
import os
from pathlib import Path
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parents[1]


def main():
    with tempfile.TemporaryDirectory(prefix="intent-retire-") as temporary:
        home = Path(temporary)
        env = {**os.environ, "HOME": str(home)}
        config = home / ".ssh/config"
        config.parent.mkdir()
        source = home / "source-config"
        config.symlink_to(source)
        snippets = config.parent / "config.d"
        snippets.mkdir()
        original = f'Include "{snippets}/*"\nHost *\n    IdentityAgent /existing/1password.sock\nHost personal\n    HostName 127.0.0.1\n'
        for project in ("keylease", "intent"):
            binary = home / ".local/bin" / project
            binary.parent.mkdir(parents=True, exist_ok=True)
            binary.write_text(f"installed {project}")
        backup = config.parent / "config.before-keylease"
        backup.write_text("original backup")

        def make(target, ok=True):
            result = subprocess.run(["make", "--no-print-directory", target, f"HOME={home}"], cwd=ROOT, env=env, capture_output=True, text=True)
            assert (result.returncode == 0) == ok, result.stdout + result.stderr
            return result

        for newline in ("", "\n"):
            user = original.rstrip("\n") + newline
            content = user
            for project in ("keylease", "intent"):
                snippet = snippets / f"{project}.conf"
                snippet.write_text("# Generated by dotfiles: one-time Mac approval for ordinary SSH connections.\nHost *\n    ControlMaster auto\n    LocalCommand obsolete\n")
                note = "# Previous config had no final newline\n" if not content.endswith("\n") else ""
                content += ("" if content.endswith("\n") else "\n") + f'# BEGIN dotfiles {project} SSH approval\n{note}Host *\n    Include "{snippet}"\n# END dotfiles {project} SSH approval\n'
            source.write_text(content)
            make("intent-ssh", ok=False)
            assert source.read_text() == content, "unsupported activation changed config"
            make("intent-ssh-remove")
            assert config.is_symlink() and source.read_text() == user
            assert not list(snippets.iterdir())
            make("keylease-ssh-remove")
            assert source.read_text() == user, "cleanup is not idempotent"
            values = subprocess.run(["ssh", "-G", "-F", str(config), "personal"], check=True, capture_output=True, text=True).stdout
            assert "identityagent /existing/1password.sock" in values
            assert "controlmaster false" in values or "controlmaster no" in values
            assert "localcommand obsolete" not in values
        assert backup.read_text() == "original backup"
        for project in ("keylease", "intent"):
            assert (home / ".local/bin" / project).read_text() == f"installed {project}"
        unmanaged = snippets / "keylease.conf"
        unmanaged.write_text("# user managed\n")
        make("intent-ssh-remove", ok=False)
        assert unmanaged.read_text() == "# user managed\n" and source.read_text() == user
        unmanaged.unlink()
        source.write_text(user + "\n# BEGIN dotfiles intent SSH approval\n")
        make("intent-ssh-remove", ok=False)
        assert source.read_text() == user + "\n# BEGIN dotfiles intent SSH approval\n"
        for ambiguous in (
            "# BEGIN dotfiles intent SSH approval\n# BEGIN dotfiles intent SSH approval\nHost valuable\n# END dotfiles intent SSH approval\n",
            "# BEGIN dotfiles intent SSH approval\n# BEGIN dotfiles keylease SSH approval\nHost valuable\n# END dotfiles keylease SSH approval\n# END dotfiles intent SSH approval\n",
        ):
            source.write_text(user + ambiguous)
            make("intent-ssh-remove", ok=False)
            assert source.read_text() == user + ambiguous, "nested managed blocks were modified"
        print("PASS: retirement preserves both binaries, user settings, symlinks, backups and final newlines; unsupported activation has no effects.")


if __name__ == "__main__":
    main()
