#!/usr/bin/env bash
# Generate completions from installed tools only; never install or initialize tools.
set -euo pipefail

setup_home=${1:-$HOME}
[[ $# == 0 ]] || shift
refresh=
action=generate
add_name=
add_command=()
usage() {
    printf '%s\n' 'Usage: recomp [add TOOL [COMMAND [ARG ...]]]' \
        '  recomp                  Regenerate completions and reload this Zsh.' \
        '  recomp add epf          Find and save a local completion generator.' \
        '  recomp add cargo rustup completions zsh cargo' \
        '                         Save an explicit generator command.'
}
case ${1:-} in
    '') ;;
    --refresh) refresh=--refresh; shift ;;
    add)
        action=add
        shift
        add_name=${1:-}
        if [[ ! $add_name =~ ^[a-zA-Z0-9_][a-zA-Z0-9_.+-]*$ ]]; then
            usage >&2
            exit 2
        fi
        shift
        add_command=("$@")
        # The registry stores literal whitespace-separated words, not shell code.
        for argument in "$@"; do
            if [[ -z $argument || $argument == *[[:space:]]* ]]; then
                printf 'Completion arguments must be nonempty words without whitespace; use an executable wrapper for more complex commands.\n' >&2
                exit 2
            fi
        done
        set --
        ;;
    -h|--help) usage; exit 0 ;;
    *) usage >&2; exit 2 ;;
esac
if [[ $# != 0 ]]; then
    usage >&2
    exit 2
fi
completion_dir="$setup_home/.zsh/completions"
registry="${XDG_CONFIG_HOME:-$setup_home/.config}/dotfiles/completions"
marker='# Generated by dotfiles/scripts/make/completions.sh'
temporary=
add_stage=
registry_temporary=
registry_lock=
changed=0
result=0
registered='|'
mkdir -p "$completion_dir"
# compinit -C trusts an existing dump, so invalidate it only when files changed
# (or recomp explicitly asks). A noninteractive installer cannot refresh its
# parent shell; the next shell rebuilds, and recomp reloads the current one.
# Also invalidate if a later filesystem operation fails or setup is interrupted.
# shellcheck disable=SC2317,SC2329 # Invoked indirectly by the EXIT trap.
finish() {
    local status=$?
    if [[ $changed == 1 || $refresh == --refresh ]]; then
        shopt -s nullglob
        rm -f -- "$setup_home"/.zcompdump* "${ZDOTDIR:-$setup_home}"/.zcompdump* "$setup_home"/.zsh/cache/zcompdump* || status=1
    fi
    [[ -z $temporary ]] || rm -f -- "$temporary" || status=1
    [[ -z $add_stage ]] || rm -rf -- "$add_stage" || status=1
    [[ -z $registry_temporary ]] || rm -f -- "$registry_temporary" || status=1
    [[ -z $registry_lock ]] || rmdir -- "$registry_lock" || status=1
    trap - EXIT
    exit "$status"
}
trap 'finish' EXIT
trap 'exit 130' INT
trap 'exit 143' TERM

valid_completion() {
    local first_line
    IFS= read -r first_line < "$1" || first_line=
    [[ $first_line == '#compdef '* || $first_line == '#autoload'* ]] || return 1
    ! command -v zsh >/dev/null 2>&1 || ZDOTDIR="$completion_dir" zsh -dfn "$1"
}

keep_existing_completion() {
    local destination="$completion_dir/_$1"
    if [[ -e $destination || -L $destination ]]; then
        if [[ -L $destination || ! -f $destination ]] || ! grep -Fxq "$marker" "$destination"; then
            printf 'Keeping existing completion: %s\n' "$destination"
            return 0
        fi
    fi
    return 1
}

install_completion() {
    local name=$1 destination="$completion_dir/_$1"
    printf '\n%s\n' "$marker" >> "$temporary"
    if ! cmp -s "$temporary" "$destination"; then
        mv -f -- "$temporary" "$destination"
        changed=1
        printf 'Updated zsh completion: %s\n' "$name"
    fi
}

# Use the caller's PATH, including bootstrap's additions, without sourcing a
# profile (which can start an SSH agent or load credentials in noninteractive setup).
# shellcheck disable=SC2329 # Invoked by the local and built-in catalog callbacks.
generate() {
    local name=${1:-}
    if [[ $# -lt 2 || ! $name =~ ^[a-zA-Z0-9_][a-zA-Z0-9_.+-]*$ ]]; then
        printf 'Invalid completion registration: expected a tool name, command and optional arguments.\n' >&2
        result=1
        return 0
    fi
    shift
    # Local registrations take precedence, without regenerating a destination
    # twice (which would invalidate the cache on every unchanged setup).
    [[ $registered != *"|$name|"* ]] || return 0
    registered+="$name|"
    command -v "$name" >/dev/null 2>&1 || return 0
    command -v "$1" >/dev/null 2>&1 || return 0
    # Files created by hand and package/user symlinks remain under their owner's
    # control. Only this script's previously generated files may be replaced.
    keep_existing_completion "$name" && return 0
    temporary=$(mktemp "$completion_dir/.$name.XXXXXX")
    if ! "$@" > "$temporary"; then
        printf 'Failed to generate zsh completion for %s; previous completion kept.\n' "$name" >&2
        result=1
    else
        if ! valid_completion "$temporary"; then
            printf 'Invalid or empty zsh completion for %s; previous completion kept.\n' "$name" >&2
            result=1
        else
            install_completion "$name"
        fi
    fi
    rm -f -- "$temporary"
    temporary=
}

# Older fd releases (including 8.3.2) can ship a completion file without
# supporting --gen-completions. Fall back only for that unsupported argument,
# not for unrelated generator failures.
# shellcheck disable=SC2317,SC2329 # Invoked indirectly by generate.
fd_completions() (
    local stage binary directory prefix candidate target
    stage=$(mktemp -d "$completion_dir/.fd.XXXXXX") || return 1
    trap 'rm -rf -- "$stage"' EXIT
    if fd --gen-completions zsh > "$stage/output" 2> "$stage/error"; then
        cat "$stage/error" >&2
        cat "$stage/output"
        return
    fi
    if grep -Eq "(unexpected argument|Found argument).*'--gen-completions'" "$stage/error"; then
        binary=$(command -v fd)
        # Debian's fd alias and Homebrew links may point to another prefix.
        while [[ -L $binary ]]; do
            target=$(readlink "$binary") || return 1
            if [[ $target == /* ]]; then binary=$target
            else binary="${binary%/*}/$target"; fi
        done
        directory=${binary%/*}
        prefix=${directory%/*}
        for candidate in \
            "$prefix/share/zsh/site-functions/_fd" \
            "$prefix/share/zsh/vendor-completions/_fd" \
            "$directory/autocomplete/_fd" \
            "${ZSH_COMPLETIONS:-${XDG_DATA_HOME:-$setup_home/.local/share}/zsh/site-functions}/_fd"; do
            [[ -f $candidate && -r $candidate ]] || continue
            cat "$candidate"
            return
        done
        printf 'This fd cannot generate completions and no packaged _fd was found. Install a newer fd or copy its packaged _fd to %s/_fd.\n' "$completion_dir" >&2
    else
        cat "$stage/error" >&2
    fi
    return 1
)

# Machine-only tools belong outside the checkout. Read literal whitespace-separated
# words, not shell code: no eval, substitutions, globbing, quoting or profile setup.
local_completions() {
    local callback=$1 line
    local -a entry
    [[ -f $registry ]] || return 0
    while IFS= read -r line || [[ -n $line ]]; do
        read -r -a entry <<< "$line"
        [[ -n ${entry[0]:-} && ${entry[0]} != \#* ]] || continue
        "$callback" "${entry[@]}"
    done < "$registry"
}

# Completion interfaces are tool-specific. Do not try arbitrary commands from
# PATH with guessed flags during setup. Explicit `recomp add` may probe only
# the requested tool. Keep the catalog shared by generation and registration.
builtin_completions() {
    local callback=$1
    "$callback" uv uv generate-shell-completion zsh
    "$callback" uvx uvx --generate-shell-completion zsh
    "$callback" rustup rustup completions zsh
    "$callback" cargo rustup completions zsh cargo
    "$callback" gh gh completion --shell zsh
    "$callback" delta delta --generate-completion zsh
    "$callback" codex codex completion zsh
    "$callback" zellij zellij setup --generate-completion zsh
    "$callback" starship starship completions zsh
    "$callback" atuin atuin gen-completions --shell zsh
    "$callback" bat bat --completion zsh
    "$callback" fd fd_completions
    "$callback" rg rg --generate complete-zsh
    "$callback" just just --completions zsh
    "$callback" glow glow completion zsh
    "$callback" yq yq shell-completion zsh
    "$callback" tree-sitter tree-sitter complete --shell zsh
}

# shellcheck disable=SC2329 # Invoked by the local and built-in catalog callbacks.
choose_generator() {
    if [[ $1 == "$add_name" && -z ${add_command[0]:-} ]]; then
        shift
        add_command=("$@")
    fi
}

save_registration() {
    local line found=0 registration="$add_name ${add_command[*]}"
    local -a entry
    # Replacing a symlink would detach someone else's managed configuration.
    if [[ -L $registry || ( -e $registry && ! -f $registry ) ]]; then
        printf 'Cannot replace completion registry; edit it directly: %s\n' "$registry" >&2
        return 1
    fi
    mkdir -p "${registry%/*}"
    # Hold the lock through publication of the matching completion file.
    if ! mkdir "$registry.lock" 2>/dev/null; then
        printf 'Completion registry is locked: %s.lock\n' "$registry" >&2
        return 1
    fi
    registry_lock="$registry.lock"
    registry_temporary=$(mktemp "$registry.XXXXXX")
    if [[ -f $registry ]]; then
        while IFS= read -r line || [[ -n $line ]]; do
            read -r -a entry <<< "$line"
            if [[ ${entry[0]:-} == "$add_name" ]]; then
                if [[ $found == 0 ]]; then
                    printf '%s\n' "$registration"
                    found=1
                fi
            else
                printf '%s\n' "$line"
            fi
        done < "$registry" > "$registry_temporary"
    fi
    [[ $found == 1 ]] || printf '%s\n' "$registration" >> "$registry_temporary"
    if ! cmp -s "$registry_temporary" "$registry"; then
        mv -f -- "$registry_temporary" "$registry"
    fi
}

try_generator() {
    if "$@" > "$temporary" 2> "$add_stage/error" && valid_completion "$temporary" 2>> "$add_stage/error"; then
        cat "$add_stage/error" >&2
        return 0
    fi
    printf 'Generator failed validation: %s\n' "$*" >> "$add_stage/attempts"
    cat "$add_stage/error" >> "$add_stage/attempts"
    return 1
}

add_completion() {
    local builtin=0 found=0 variant
    if ! command -v "$add_name" >/dev/null 2>&1; then
        printf 'Completion target is not on PATH: %s\n' "$add_name" >&2
        return 1
    fi
    if [[ -z ${add_command[0]:-} ]]; then
        local_completions choose_generator
        if [[ -z ${add_command[0]:-} ]]; then
            builtin_completions choose_generator
            [[ -z ${add_command[0]:-} ]] || builtin=1
        fi
    fi
    add_stage=$(mktemp -d "$completion_dir/.add.XXXXXX")
    temporary="$add_stage/output"
    if [[ -n ${add_command[0]:-} ]]; then
        if ! command -v "${add_command[0]}" >/dev/null 2>&1; then
            printf 'Completion generator is not on PATH: %s\n' "${add_command[0]}" >&2
            return 1
        fi
        if try_generator "${add_command[@]}"; then found=1; fi
    else
        for variant in completions completion; do
            add_command=("$add_name" "$variant" zsh)
            if try_generator "${add_command[@]}"; then found=1; break; fi
        done
    fi
    if [[ $found == 0 ]]; then
        cat "$add_stage/attempts" >&2
        printf 'No valid Zsh completion for %s; registry and previous completion kept. Specify a generator with: recomp add %s COMMAND [ARG ...]\n' "$add_name" "$add_name" >&2
        return 1
    fi
    if [[ $builtin == 1 ]]; then
        printf 'Using built-in completion generator: %s\n' "$add_name"
    else
        save_registration
        printf 'Registered %s in %s\n' "$add_name" "$registry"
    fi
    keep_existing_completion "$add_name" || install_completion "$add_name"
    refresh=--refresh
}

if [[ $action == add ]]; then
    add_completion
else
    local_completions generate
    builtin_completions generate
fi

exit "$result"
