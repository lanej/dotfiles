#!/usr/bin/env bash
# Generate completions from installed tools only; never install or initialize tools.
set -euo pipefail

setup_home=${1:-$HOME}
refresh=${2:-}
if [[ -n $refresh && $refresh != --refresh ]]; then
    printf 'Usage: %s [home] [--refresh]\n' "$0" >&2
    exit 2
fi
completion_dir="$setup_home/.zsh/completions"
marker='# Generated by dotfiles/scripts/make/completions.sh'
temporary=
changed=0
result=0
registered='|'
mkdir -p "$completion_dir"
# compinit -C trusts an existing dump, so invalidate it only when files changed
# (or recomp explicitly asks). A noninteractive installer cannot refresh its
# parent shell; the next shell rebuilds, and recomp reloads the current one.
# Also invalidate if a later filesystem operation fails or setup is interrupted.
# shellcheck disable=SC2317,SC2329 # Invoked indirectly by the EXIT trap.
finish() {
    local status=$?
    if [[ $changed == 1 || $refresh == --refresh ]]; then
        shopt -s nullglob
        rm -f -- "$setup_home"/.zcompdump* "${ZDOTDIR:-$setup_home}"/.zcompdump* "$setup_home"/.zsh/cache/zcompdump* || status=1
    fi
    [[ -z $temporary ]] || rm -f -- "$temporary" || status=1
    trap - EXIT
    exit "$status"
}
trap 'finish' EXIT
trap 'exit 130' INT
trap 'exit 143' TERM

# Use the caller's PATH, including bootstrap's additions, without sourcing a
# profile (which can start an SSH agent or load credentials in noninteractive setup).
generate() {
    local name=${1:-} destination first_line
    if [[ $# -lt 2 || ! $name =~ ^[a-zA-Z0-9_][a-zA-Z0-9_.+-]*$ ]]; then
        printf 'Invalid completion registration: expected a tool name, command and optional arguments.\n' >&2
        result=1
        return 0
    fi
    shift
    # Local registrations take precedence, without regenerating a destination
    # twice (which would invalidate the cache on every unchanged setup).
    [[ $registered != *"|$name|"* ]] || return 0
    registered+="$name|"
    command -v "$name" >/dev/null 2>&1 || return 0
    command -v "$1" >/dev/null 2>&1 || return 0
    destination="$completion_dir/_$name"
    # Files created by hand and package/user symlinks remain under their owner's
    # control. Only this script's previously generated files may be replaced.
    if [[ -e $destination || -L $destination ]]; then
        if [[ -L $destination || ! -f $destination ]] || ! grep -Fxq "$marker" "$destination"; then
            printf 'Keeping existing completion: %s\n' "$destination"
            return 0
        fi
    fi
    temporary=$(mktemp "$completion_dir/.$name.XXXXXX")
    if ! "$@" > "$temporary"; then
        printf 'Failed to generate zsh completion for %s; previous completion kept.\n' "$name" >&2
        result=1
    else
        IFS= read -r first_line < "$temporary" || first_line=
        if [[ $first_line != '#compdef '* && $first_line != '#autoload'* ]] ||
            { command -v zsh >/dev/null 2>&1 && ! ZDOTDIR="$completion_dir" zsh -dfn "$temporary"; }; then
            printf 'Invalid or empty zsh completion for %s; previous completion kept.\n' "$name" >&2
            result=1
        else
            printf '\n%s\n' "$marker" >> "$temporary"
            if ! cmp -s "$temporary" "$destination"; then
                mv -f -- "$temporary" "$destination"
                changed=1
                printf 'Updated zsh completion: %s\n' "$name"
            fi
        fi
    fi
    rm -f -- "$temporary"
    temporary=
}

# Older fd releases (including 8.3.2) can ship a completion file without
# supporting --gen-completions. Fall back only for that unsupported argument,
# not for unrelated generator failures.
# shellcheck disable=SC2317,SC2329 # Invoked indirectly by generate.
fd_completions() (
    local stage binary directory prefix candidate target
    stage=$(mktemp -d "$completion_dir/.fd.XXXXXX") || return 1
    trap 'rm -rf -- "$stage"' EXIT
    if fd --gen-completions zsh > "$stage/output" 2> "$stage/error"; then
        cat "$stage/error" >&2
        cat "$stage/output"
        return
    fi
    if grep -Eq "(unexpected argument|Found argument).*'--gen-completions'" "$stage/error"; then
        binary=$(command -v fd)
        # Debian's fd alias and Homebrew links may point to another prefix.
        while [[ -L $binary ]]; do
            target=$(readlink "$binary") || return 1
            if [[ $target == /* ]]; then binary=$target
            else binary="${binary%/*}/$target"; fi
        done
        directory=${binary%/*}
        prefix=${directory%/*}
        for candidate in \
            "$prefix/share/zsh/site-functions/_fd" \
            "$prefix/share/zsh/vendor-completions/_fd" \
            "$directory/autocomplete/_fd" \
            "${ZSH_COMPLETIONS:-${XDG_DATA_HOME:-$setup_home/.local/share}/zsh/site-functions}/_fd"; do
            [[ -f $candidate && -r $candidate ]] || continue
            cat "$candidate"
            return
        done
        printf 'This fd cannot generate completions and no packaged _fd was found. Install a newer fd or copy its packaged _fd to %s/_fd.\n' "$completion_dir" >&2
    else
        cat "$stage/error" >&2
    fi
    return 1
)

# Machine-only tools belong outside the checkout. Read literal whitespace-separated
# words, not shell code: no eval, substitutions, globbing, quoting or profile setup.
registry="${XDG_CONFIG_HOME:-$setup_home/.config}/dotfiles/completions"
if [[ -f $registry ]]; then
    while IFS= read -r line || [[ -n $line ]]; do
        read -r -a entry <<< "$line"
        [[ -n ${entry[0]:-} && ${entry[0]} != \#* ]] || continue
        generate "${entry[@]}"
    done < "$registry"
fi

# Completion interfaces are tool-specific. Do not try arbitrary commands from
# PATH with guessed flags. Tools without generators retain their packaged zsh
# site-functions and shell integrations (for example eza, git and fzf).
generate uv uv generate-shell-completion zsh
generate uvx uvx --generate-shell-completion zsh
generate rustup rustup completions zsh
generate cargo rustup completions zsh cargo
generate gh gh completion --shell zsh
generate delta delta --generate-completion zsh
generate codex codex completion zsh
generate zellij zellij setup --generate-completion zsh
generate starship starship completions zsh
generate atuin atuin gen-completions --shell zsh
generate bat bat --completion zsh
generate fd fd_completions
generate rg rg --generate complete-zsh
generate just just --completions zsh
generate glow glow completion zsh
generate yq yq shell-completion zsh
generate tree-sitter tree-sitter complete --shell zsh

exit "$result"
