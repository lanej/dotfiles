#!/usr/bin/env python3
"""Configure automatic, connection-scoped Keylease approval without replacing SSH settings."""
import argparse
import os
from pathlib import Path
import platform
import re
import shlex
import shutil
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parents[1]
BEGIN = "# BEGIN dotfiles keylease SSH approval"
END = "# END dotfiles keylease SSH approval"
BLOCK = re.compile(r"(?m)^" + re.escape(BEGIN) + r"\n.*?^" + re.escape(END) + r"\n?", re.S)
OWNER = "# Generated by dotfiles: one-time Mac approval"
NO_NEWLINE = "# Previous config had no final newline"


def atomic_write(path, content):
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, temporary = tempfile.mkstemp(prefix=".keylease-", dir=path.parent)
    try:
        with os.fdopen(fd, "w") as stream:
            stream.write(content)
        os.chmod(temporary, 0o600)
        os.replace(temporary, path)
    finally:
        Path(temporary).unlink(missing_ok=True)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--keylease", default=str(Path.home() / ".local/bin/keylease"))
    parser.add_argument("--remove", action="store_true")
    args = parser.parse_args()
    home = Path.home()
    ssh_dir = home / ".ssh"
    config = ssh_dir / "config"
    if config.is_symlink() and not config.exists():
        raise ValueError(f"Preserve dangling SSH config symlink: {config}")
    target = config.resolve()
    original = target.read_text() if target.exists() else ""
    if (BEGIN in original or END in original) and len(BLOCK.findall(original)) != 1:
        raise ValueError("Malformed Keylease SSH block; preserve config and repair it manually")
    unmanaged = original
    match_block = BLOCK.search(original)
    if match_block:
        start, end = match_block.span()
        if NO_NEWLINE in match_block.group() and start and original[start - 1] == "\n":
            start -= 1
        unmanaged = original[:start] + original[end:]
    snippet = ssh_dir / "config.d/keylease.conf"
    if snippet.is_symlink() or (snippet.exists() and not snippet.read_text().startswith(OWNER)):
        raise ValueError(f"Preserve unmanaged SSH snippet: {snippet}")
    if args.remove:
        if original != unmanaged:
            atomic_write(target, unmanaged)
        snippet.unlink(missing_ok=True)
        print("Removed Keylease SSH configuration; existing SSH settings preserved.")
        return
    if platform.system() != "Darwin":
        raise ValueError("Configure outgoing native approval on the Mac; remote Linux callers only need Keylease installed")
    binary = Path(args.keylease).expanduser().absolute()
    if not binary.is_file() or not os.access(binary, os.X_OK):
        raise ValueError(f"Install the updated Keylease binary first: {binary}")
    check = subprocess.run([str(binary), "approval", "ssh-hook", "--help"], capture_output=True, text=True)
    if check.returncode or "-control" not in check.stderr:
        raise ValueError("Installed Keylease lacks the SSH config hook; build and install the updated Keylease branch")
    helper = binary.resolve().parent / "Approval.app/Contents/MacOS/Approval"
    if not helper.is_file():
        raise ValueError(f"Native approval app is missing: {helper}")
    ssh = shutil.which("ssh")
    if not ssh:
        raise ValueError("OpenSSH is required")
    version = subprocess.run([ssh, "-V"], capture_output=True, text=True, check=True)
    match = re.search(r"OpenSSH_(\d+)\.(\d+)", version.stdout + version.stderr)
    if not match or tuple(map(int, match.groups())) < (10, 3):
        raise ValueError("Automatic approval needs OpenSSH 10.3+ for local connection labels")
    control = ssh_dir / "keylease-control"
    if len(os.fsencode(str(control))) + 1 + 40 >= 100:
        raise ValueError("SSH control directory path is too long for Unix sockets")
    if control.is_symlink():
        raise ValueError(f"Preserve symlinked SSH control directory: {control}")
    if control.exists() and (not control.is_dir() or control.stat().st_uid != os.getuid()):
        raise ValueError(f"Preserve unowned SSH control directory: {control}")
    template = (ROOT / "ssh/keylease.conf.template").read_text()
    # Only %C (OpenSSH's hexadecimal route hash) is substituted at connection
    # time. Hostnames never enter a LocalCommand shell command.
    rendered = template.replace("__CONTROL_SHELL__", shlex.quote(str(control)))
    rendered = rendered.replace("__CONTROL__", str(control).replace('\\', '\\\\').replace('"', '\\"'))
    rendered = rendered.replace("__KEYLEASE__", shlex.quote(str(binary)))
    include = '"' + str(snippet).replace("\\", "\\\\").replace('"', '\\"') + '"'
    separator_note = NO_NEWLINE + "\n" if unmanaged and not unmanaged.endswith("\n") else ""
    managed = f"{BEGIN}\n{separator_note}Host *\n    Include {include}\n{END}\n"
    updated = unmanaged + ("" if not unmanaged or unmanaged.endswith("\n") else "\n") + managed
    # Validate the staged configuration and its effective control settings before
    # touching the live config. Earlier user settings retain SSH precedence.
    with tempfile.TemporaryDirectory(prefix="keylease-ssh-config-") as scratch:
        stage = Path(scratch)
        staged_snippet = stage / "keylease.conf"
        staged_snippet.write_text(rendered)
        staged_config = stage / "config"
        staged_config.write_text(updated.replace(str(snippet), str(staged_snippet)))
        result = subprocess.run([ssh, "-G", "-F", str(staged_config), "keylease-config-check.invalid"], capture_output=True, text=True, check=True)
        effective = dict(line.split(" ", 1) for line in result.stdout.splitlines() if " " in line)
        if effective.get("controlmaster") not in ("auto", "true", "yes") or effective.get("permitlocalcommand") != "yes" or str(control) not in effective.get("controlpath", "") or str(binary) not in effective.get("localcommand", ""):
            raise ValueError("Existing SSH settings override automatic approval; reconcile ControlMaster, ControlPath, PermitLocalCommand or LocalCommand before enabling")
    ssh_dir.mkdir(mode=0o700, parents=True, exist_ok=True)
    control.mkdir(mode=0o700, exist_ok=True)
    os.chmod(control, 0o700)
    if original != updated and target.exists():
        backup = target.with_name(target.name + ".before-keylease")
        if not backup.exists():
            atomic_write(backup, original)
    atomic_write(snippet, rendered)
    if original != updated:
        atomic_write(target, updated)
    print(f"Configured Keylease approval for new SSH connections in {config}.")
    print("Remote hosts need the updated Keylease binary on their noninteractive SSH PATH.")


if __name__ == "__main__":
    try:
        main()
    except (OSError, ValueError, subprocess.CalledProcessError) as error:
        raise SystemExit(f"keylease-ssh: {error}")
