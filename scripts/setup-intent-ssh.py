#!/usr/bin/env python3
"""Retire obsolete managed SSH approval hooks while preserving both installed tools."""
import argparse
import os
from pathlib import Path
import re
import tempfile

BEGIN = "# BEGIN dotfiles intent SSH approval"
END = "# END dotfiles intent SSH approval"
BLOCK = re.compile(r"(?m)^" + re.escape(BEGIN) + r"\n.*?^" + re.escape(END) + r"\n?", re.S)
OWNER = "# Generated by dotfiles: one-time Mac approval"
NO_NEWLINE = "# Previous config had no final newline"


def atomic_write(path, content):
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, temporary = tempfile.mkstemp(prefix=".intent-", dir=path.parent)
    try:
        with os.fdopen(fd, "w") as stream:
            stream.write(content)
        os.chmod(temporary, 0o600)
        os.replace(temporary, path)
    finally:
        Path(temporary).unlink(missing_ok=True)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--remove", action="store_true")
    args = parser.parse_args()
    if not args.remove:
        raise ValueError("Automatic SSH approval is pending production integration of the stable-socket design; see docs/intent-ssh.md. Use --remove to retire the old managed hooks.")
    home = Path.home()
    ssh_dir = home / ".ssh"
    config = ssh_dir / "config"
    if config.is_symlink() and not config.exists():
        raise ValueError(f"Preserve dangling SSH config symlink: {config}")
    target = config.resolve()
    original = target.read_text() if target.exists() else ""
    if (BEGIN in original or END in original) and len(BLOCK.findall(original)) != 1:
        raise ValueError("Malformed Intent SSH block; preserve config and repair it manually")
    unmanaged = original
    legacy_begin = "# BEGIN dotfiles keylease SSH approval"
    legacy_end = "# END dotfiles keylease SSH approval"
    legacy_block = re.compile(r"(?m)^" + re.escape(legacy_begin) + r"\n.*?^" + re.escape(legacy_end) + r"\n?", re.S)
    markers = {BEGIN: END, legacy_begin: legacy_end}
    active = None
    seen = set()
    for line in original.splitlines():
        if line in markers:
            if active is not None or line in seen:
                raise ValueError("Malformed managed SSH blocks; preserve config and repair them manually")
            active = line
            seen.add(line)
        elif line in markers.values():
            if active is None or markers[active] != line:
                raise ValueError("Malformed managed SSH blocks; preserve config and repair them manually")
            active = None
    if active is not None:
        raise ValueError("Malformed managed SSH blocks; preserve config and repair them manually")
    for begin, end, block in ((BEGIN, END, BLOCK), (legacy_begin, legacy_end, legacy_block)):
        if (begin in unmanaged or end in unmanaged) and len(block.findall(unmanaged)) != 1:
            raise ValueError("Malformed managed SSH block; preserve config and repair it manually")
        match_block = block.search(unmanaged)
        if match_block:
            start, stop = match_block.span()
            if NO_NEWLINE in match_block.group() and start and unmanaged[start - 1] == "\n":
                start -= 1
            unmanaged = unmanaged[:start] + unmanaged[stop:]
    legacy_snippet = ssh_dir / "config.d/keylease.conf"
    if legacy_snippet.is_symlink() or (legacy_snippet.exists() and not legacy_snippet.read_text().startswith(OWNER)):
        raise ValueError(f"Preserve unmanaged SSH snippet: {legacy_snippet}")
    snippet = ssh_dir / "config.d/intent.conf"
    if snippet.is_symlink() or (snippet.exists() and not snippet.read_text().startswith(OWNER)):
        raise ValueError(f"Preserve unmanaged SSH snippet: {snippet}")
    if original != unmanaged:
        atomic_write(target, unmanaged)
    snippet.unlink(missing_ok=True)
    legacy_snippet.unlink(missing_ok=True)
    print("Removed obsolete SSH approval hooks; Intent and Keylease installations and active sessions are preserved.")


if __name__ == "__main__":
    try:
        main()
    except (OSError, ValueError) as error:
        raise SystemExit(f"intent-ssh: {error}")
