import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { load } from "js-yaml";

const source = new URL("../api/beads-1.3.4.yaml", import.meta.url);
const target = new URL(
  "../../../nvim/lua/beads/generated.lua",
  import.meta.url,
);
const spec = load(readFileSync(source, "utf8"));
const selected = new Set([
  "getContext",
  "listIssues",
  "getIssue",
  "updateIssue",
  "listDependencies",
  "getSetting",
  "applyBatch",
  "closeIssue",
  "reopenIssue",
]);
const schemas = {};
const supported = new Set([
  "$ref",
  "type",
  "properties",
  "items",
  "required",
  "additionalProperties",
  "nullable",
  "enum",
  "minLength",
  "maxLength",
  "minimum",
  "maximum",
  "minItems",
  "maxItems",
  "format",
  "pattern",
  "default",
]);
function resolve(value) {
  if (!value?.$ref) return value;
  if (!value.$ref.startsWith("#/"))
    throw new Error("Only local schema refs are supported");
  return value.$ref
    .slice(2)
    .split("/")
    .reduce((v, key) => v[key], spec);
}
function schema(value) {
  if (typeof value === "boolean") return value;
  const result = {};
  for (const [key, item] of Object.entries(value)) {
    if (
      [
        "description",
        "title",
        "example",
        "examples",
        "deprecated",
        "readOnly",
        "writeOnly",
      ].includes(key) ||
      key.startsWith("x-")
    )
      continue;
    if (!supported.has(key))
      throw new Error(`Unsupported schema keyword: ${key}`);
    if (key === "$ref") {
      const name = item.replace("#/components/schemas/", "");
      if (name === item) throw new Error(`Unsupported reference: ${item}`);
      result.$ref = name;
      if (!Object.hasOwn(schemas, name)) {
        schemas[name] = {};
        schemas[name] = schema(resolve(value));
      }
    } else if (key === "properties") {
      result.properties = Object.fromEntries(
        Object.entries(item).map(([k, v]) => [k, schema(v)]),
      );
    } else if (
      key === "items" ||
      (key === "additionalProperties" && typeof item === "object")
    ) {
      result[key] = schema(item);
    } else result[key] = item;
  }
  return result;
}
const operations = {};
for (const [path, methods] of Object.entries(spec.paths)) {
  for (const [method, op] of Object.entries(methods)) {
    if (!selected.delete(op.operationId)) continue;
    const params = [...(methods.parameters ?? []), ...(op.parameters ?? [])]
      .map(resolve)
      .map((p) => ({
        name: p.name,
        location: p.in,
        required: p.required === true,
        schema: schema(p.schema),
        ...(p.style ? { style: p.style } : {}),
        ...(p.explode !== undefined ? { explode: p.explode } : {}),
      }));
    const body = resolve(op.requestBody)?.content?.["application/json"]?.schema;
    const response = resolve(op.responses["200"])?.content?.["application/json"]
      ?.schema;
    if (!response)
      throw new Error(`No JSON 200 response for ${op.operationId}`);
    operations[op.operationId] = {
      method: method.toUpperCase(),
      path,
      params,
      ...(body ? { body: schema(body) } : {}),
      response: schema(response),
    };
  }
}
if (selected.size) throw new Error(`Missing operations: ${[...selected]}`);
function luaType(s) {
  if (s.$ref) return `beads.api.${s.$ref}`;
  if (s.enum) return s.enum.map((v) => JSON.stringify(v)).join("|");
  if (s.type === "array") return `(${luaType(s.items)})[]`;
  if (s.type === "object") return "table";
  return (
    {
      integer: "number",
      number: "number",
      boolean: "boolean",
      string: "string",
    }[s.type] ?? "any"
  );
}
const types = Object.entries(schemas)
  .sort(([a], [b]) => a.localeCompare(b))
  .flatMap(([name, s]) => {
    if (s.type !== "object")
      return [`---@alias beads.api.${name} ${luaType(s)}`];
    return [
      `---@class beads.api.${name}`,
      ...Object.entries(s.properties ?? {}).map(
        ([key, p]) =>
          `---@field ${key}${s.required?.includes(key) ? "" : "?"} ${luaType(p)}${p.nullable ? "|nil" : ""}`,
      ),
    ];
  });
const output = `-- Generated by tools/task-runtime/scripts/generate-beads-lua.mjs; do not edit.\n${types.join("\n")}\nreturn vim.json.decode([=[\n${JSON.stringify({ operations, schemas }, null, 2)}\n]=])\n`;
if (process.argv.includes("--check")) {
  if (readFileSync(target, "utf8") !== output)
    throw new Error(`Stale generated bindings: ${fileURLToPath(target)}`);
} else writeFileSync(target, output);
